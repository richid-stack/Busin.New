// Builds server/services/documents/fonts.generated.ts: the Noto Sans files (SIL Open Font License) that
// PDF export embeds, as base64, so they ship inside the server bundle. Latin covers everyday text;
// Latin Extended adds letters such as the cedi sign and Twi/Ewe letters. Run `npm run fonts` to rebuild.
import { readFileSync, writeFileSync } from 'node:fs'

const dir = 'node_modules/@fontsource/noto-sans/files/'
const files = {
  latinRegular: 'noto-sans-latin-400-normal.woff',
  latinBold: 'noto-sans-latin-700-normal.woff',
  extRegular: 'noto-sans-latin-ext-400-normal.woff',
  extBold: 'noto-sans-latin-ext-700-normal.woff'
}
let out = '// Generated by scripts/build-fonts.mjs. Do not edit. Noto Sans, SIL Open Font License 1.1.\n'
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = '${readFileSync(dir + file).toString('base64')}'\n`
}
writeFileSync('server/services/documents/fonts.generated.ts', out)
console.log('fonts written')
