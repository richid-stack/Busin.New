// Bundles runner/github.ts into one file and writes it into server/services/cloudbox/githubRunnerScript.generated.ts,
// so the server can put the exact same script into a person's openlobs-runs repo. Run: npm run build:github-runner
// A test rebuilds it and fails if the committed copy is out of date.
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { rolldown } from 'rolldown'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUT = path.join(root, 'server/services/cloudbox/githubRunnerScript.generated.ts')

export async function buildRunnerScript() {
  const bundle = await rolldown({ input: path.join(root, 'runner/github.ts'), platform: 'node', logLevel: 'silent' })
  const { output } = await bundle.generate({ format: 'esm', minify: true, codeSplitting: false })
  await bundle.close()
  const code = output.find(o => o.type === 'chunk')?.code
  if (!code) throw new Error('Nothing was built.')
  const script = `// OpenLobs run script. Built from runner/github.ts; the readable source is in the OpenLobs repository.\n${code}`
  const version = createHash('sha256').update(script).digest('hex').slice(0, 12)
  const file = `// GENERATED by scripts/build-github-runner.mjs from runner/github.ts. Do not edit; run: npm run build:github-runner\nexport const RUNNER_SCRIPT = ${JSON.stringify(script)}\nexport const RUNNER_SCRIPT_VERSION = ${JSON.stringify(version)}\n`
  return { file, script, version }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { file, script, version } = await buildRunnerScript()
  fs.writeFileSync(OUT, file)
  console.log(`Wrote ${path.relative(root, OUT)}: ${(script.length / 1024).toFixed(0)} KB, version ${version}`)
}
